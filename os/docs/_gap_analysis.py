#!/usr/bin/env python3
"""
Expanded gap analysis. Probes a much wider catalogue of real desktop-Linux
capabilities against the actual KorrinOS tree and reports what is ABSENT.
No entry is invented: each is a capability shipped by mainstream distros
(Debian/Ubuntu, Fedora, Arch, openSUSE, NixOS) or required for a complete
install. A presence probe is run so rows are measured, not assumed.
"""
import os
import sys

ROOT = "/home/tinkerspace/linux-kernel/os"

corpus = []
for dirpath, dirnames, filenames in os.walk(ROOT):
    dirnames[:] = [d for d in dirnames if d not in (".git", "node_modules", "dist")]
    for fn in filenames:
        p = os.path.join(dirpath, fn)
        try:
            if os.path.getsize(p) > 400_000:
                continue
            with open(p, encoding="utf-8", errors="ignore") as fh:
                corpus.append(fh.read().lower())
        except OSError:
            pass
BLOB = "\n".join(corpus)
print(f"corpus: {len(corpus)} files, {len(BLOB)} chars", file=sys.stderr)


def present(*needles):
    return any(n.lower() in BLOB for n in needles)


C = []  # (category, name, needles)

def cat(name, items):
    for it in items:
        if isinstance(it, str):
            C.append((name, it, [it.lower()]))
        else:
            n, nd = it
            C.append((name, n, nd))

